#!/usr/bin/env python3
# Builds the shipped Italian table, src/i18n_it.js, from tools/it_table.json (English key -> Italian, the same keys as
# the Russian table: $t(s) -> s, $tx(ctx, s) -> ctx + U+0004 + s, $tn(one, many, n) -> one + U+0004 + many, and
# 'short' + U+0004 + s for the compact labels). Plurals are {"one": ..., "other": ...} (Intl.PluralRules('it'): one
# for 1, other for everything else; i18n.js falls back to 'other' for 'many').
#     python3 tools/make_it_table.py            (writes src/i18n_it.js; reports keys the Russian table has and the
#                                                Italian one lacks, which then show in English)
#     python3 tools/make_it_table.py --strict   (also fails on a missing key or a placeholder / TeX / HTML mismatch)
# Re-run it when tools/it_table.json changes; a new $t() string needs an Italian entry there (its key: the English).
import json, re, sys, pathlib

root = pathlib.Path(__file__).resolve().parent.parent
CTX = '\u0004'
src = json.loads((root / 'tools' / 'it_table.json').read_text(encoding='utf-8'))
table = {k: v for k, v in src.items() if not k.startswith('_')}

# the Russian table's keys: every string the Russian interface translates, which the Italian one should translate too
ru_js = (root / 'src' / 'i18n_ru.js').read_text(encoding='utf-8')
m = re.search(r"^I18N\.define\('ru', (\".*\")\);\s*$", ru_js, re.S | re.M)
ru = json.loads(json.loads(m.group(1)))


def phs(s):
    """i18n.js's placeholder rule: %{name} always, {name} only in a template without TeX"""
    tex = re.search(r'[$\\]', s) is not None
    out = []
    for mm in re.finditer(r'%\{([A-Za-z_][A-Za-z0-9_]*)\}|\{([A-Za-z_][A-Za-z0-9_]*)\}', s):
        if mm.group(1):
            out.append('%' + mm.group(1))
        elif not tex:
            out.append(mm.group(2))
    return sorted(out)


def shape(s):
    """what a translation must keep: placeholders, TeX commands and groups ({n} in ^{n}; the words of \\text{...} are
    translated), $ count, HTML tags and entities"""
    groups = re.findall(r'%?\{[A-Za-z_][A-Za-z0-9_]*\}', re.sub(r'\\text\{[^{}%]*\}', r'\\text{}', s))
    return (phs(s), sorted(groups), sorted(re.findall(r'\\[A-Za-z]+', s)),
            s.count('$'), re.findall(r'</?[a-zA-Z][^>]*>', s), sorted(re.findall(r'&[a-zA-Z#0-9]+;', s)))


problems = []
for k, v in table.items():
    parts = k.split(CTX)
    if isinstance(v, dict):
        if len(parts) != 2 or not isinstance(v.get('one'), str) or not isinstance(v.get('other'), str):
            problems.append(f'{k!r}: a plural needs a key one + U+0004 + many and {{one, other}}')
            continue
        for en, it in ((parts[0], v['one']), (parts[1], v['other'])):
            if shape(en) != shape(it):
                problems.append(f'{k!r}: placeholders / TeX / HTML differ from the English ({it!r})')
    elif isinstance(v, str):
        en = parts[-1]
        if parts[0] == 'short' and len(parts) > 1:
            # a compact label may leave a placeholder out (the Russian «образ» for "image, after {n} steps"), never add one
            if not set(phs(v)) <= set(phs(en)) or not set(phs(v)) <= set(phs(parts[1])):
                problems.append(f'{k!r}: a short label with a placeholder its English does not have ({v!r})')
        elif shape(en) != shape(v):
            problems.append(f'{k!r}: placeholders / TeX / HTML differ from the English ({v!r})')
    else:
        problems.append(f'{k!r}: not a string or a plural')
missing = sorted(k for k in ru if k not in table)
extra = sorted(k for k in table if k not in ru)

out = root / 'src' / 'i18n_it.js'
blob = json.dumps(table, ensure_ascii=False, separators=(',', ':'), sort_keys=True)
lit = json.dumps(blob, ensure_ascii=False).replace('</', '<\\/').replace('\u2028', '\\u2028').replace('\u2029', '\\u2029')
with open(out, 'w', encoding='utf-8', newline='\n') as f:
    f.write("'use strict';\n"
            "// GENERATED by tools/make_it_table.py from tools/it_table.json: do not edit. The Italian table as one JSON string;\n"
            "// i18n.js parses it on the first Italian lookup, English never does.\n"
            f"I18N.define('it', {lit});\n")
print(f'{out.relative_to(root)}: {len(table)} entries, {out.stat().st_size} bytes; missing (shown in English) {len(missing)}, '
      f'not in the Russian table {len(extra)}, problems {len(problems)}')
for p in problems[:40]:
    print('  PROBLEM', p)
for k in missing[:40]:
    print('  MISSING', json.dumps(k, ensure_ascii=False)[:150])
if '--strict' in sys.argv and (problems or missing):
    sys.exit('the Italian table is incomplete or inconsistent')
